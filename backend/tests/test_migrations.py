"""Schema migrations.

Two properties are worth pinning, because both are easy to get wrong and
invisible in a local run:

1. The migration reproduces the models. ``0001_initial`` was generated by
   ``alembic revision --autogenerate``, so it is only correct as long as it stays
   in sync with ``Base.metadata``. This test builds the schema both ways вЂ” from
   the migration and from the ORM вЂ” into two throwaway databases and compares
   them. If someone edits a model without writing a migration, or edits the
   migration by hand and changes a type, this fails.

2. Stamping, not upgrading, for a database that already has tables. The
   application runs ``create_all`` before migrating so that databases made by
   earlier builds still open. Replaying ``0001_initial`` on such a database would
   abort on the first existing table, so the first run records the revision
   instead. The test covers that path and the idempotent second run.
"""

