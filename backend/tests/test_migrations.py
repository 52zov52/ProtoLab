ALEMBIC_INI = Path(__file__).resolve().parents[1] / "alembic.ini"


def _config(database_url: str) -> Config:
    config = Config(str(ALEMBIC_INI))
    config.attributes["mp_database_url"] = database_url
    return config


def _schema(engine) -> dict[str, dict]:
    """A comparable picture of a database: tables, columns, and constraints."""
    inspector = inspect(engine)
    tables: dict[str, dict] = {}
    for table in sorted(inspector.get_table_names()):
        if table == "alembic_version":
            continue
        tables[table] = {
            "columns": {
                column["name"]: (str(column["type"]), column["nullable"])
                for column in inspector.get_columns(table)
            },
            "pk": sorted(inspector.get_pk_constraint(table)["constrained_columns"]),
            "uniques": sorted(
                sorted(constraint["column_names"])
                for constraint in inspector.get_unique_constraints(table)
            ),
            "indexes": sorted(
                (index["name"], tuple(index["column_names"]))
                for index in inspector.get_indexes(table)
            ),
            "foreign_keys": sorted(
                (
                    foreign_key["constrained_columns"],
                    foreign_key["referred_table"],
                    foreign_key["referred_columns"],
                )
                for foreign_key in inspector.get_foreign_keys(table)
            ),
        }
    return tables


def test_migration_reproduces_the_models(tmp_path):
    from_models = create_engine(url=f"sqlite:///{tmp_path / 'models.db'}")
    Base.metadata.create_all(from_models)

    migration_url = f"sqlite:///{tmp_path / 'migrated.db'}"
    migrated = create_engine(url=migration_url)
    command.upgrade(_config(migration_url), "head")

    try:
        expected = _schema(from_models)
        actual = _schema(migrated)
        assert actual == expected
        # A trivially-empty comparison would also pass, which proves nothing.
        assert len(expected) >= 20
    finally:
        from_models.dispose()
        migrated.dispose()


def test_existing_database_is_stamped_not_replayed(tmp_path):
    """`create_all` then migrate must not abort on the tables it just made."""
    url = f"sqlite:///{tmp_path / 'existing.db'}"
    engine = create_engine(url=url)

    try:
        Base.metadata.create_all(engine)

        run_migrations(engine)

        with engine.connect() as connection:
            revision = connection.exec_driver_sql(
                "SELECT version_num FROM alembic_version"
            ).scalar_one()
        assert revision == "0001"

        # A second start is a no-op, not an "already exists" failure.
        run_migrations(engine)

        command.check(_config(url))  # no pending revisions
        assert _schema(engine)  # and the tables are still there
    finally:
        engine.dispose()


def test_migration_is_downgradable(tmp_path):
    """`downgrade` must exist, so a bad deployment can be rolled back."""
    url = f"sqlite:///{tmp_path / 'downgrade.db'}"
    engine = create_engine(url=url)

    try:
        command.upgrade(_config(url), "head")
        assert len(_schema(engine)) >= 20
        command.downgrade(_config(url), "base")
        assert _schema(engine) == {}
    finally:
        engine.dispose()
