"""Prose the API hands to the UI verbatim.

Every string here is rendered straight into the interface, so each one is a
translation key as much as it is a message: the frontend's catalogue is keyed by
the English source text, and ``tests/test_prose_localization.py`` fails when a
string is changed without its translation.

Keeping them in one module rather than inline in a router is what makes that
test possible: the English has to be importable to be checkable.

Nothing here is a protocol name, an enum value or a verdict - those are data and
stay untranslated on purpose, because translating a protocol name would make it
unsearchable.
"""

